<script setup>
import { computed } from 'vue';

const emit = defineEmits(['update:checked']);

const props = defineProps({
    checked: {
        type: [Array, Boolean],
        required: true,
    },
    value: {
        default: null,
    },
});

const proxyChecked = computed({
    get() {
        return props.checked;
    },

    set(val) {
        emit('update:checked', val);
    },
});
</script>

<template>
    <input
        type="checkbox"
        :value="value"
        v-model="proxyChecked"
        class="w-4 h-4 rounded border-surface-700 bg-surface-950 text-brand-500 shadow-sm focus:ring-brand-500 focus:ring-offset-surface-900 focus:ring-offset-1 transition-colors cursor-pointer"
    />
</template>
